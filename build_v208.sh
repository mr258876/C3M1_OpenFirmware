#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
variant="${1:-CAM1000}"
case "$variant" in
 CAM1000) cam=1000; diag=0;;
 CAM1000_DIAG) cam=1000; diag=1;;
 REF950) cam=950; diag=0;;
 *) echo 'usage: build_v208.sh CAM1000|CAM1000_DIAG|REF950' >&2; exit 2;;
esac
export C3_BOOT_OVERLAP=1 C3_BOOT_DIAG=$diag C3_LCD_POWER_SETTLE_MS=500
export C3_CAM_POWER_SETTLE_MS=$cam C3_ZOOM_LOCK_DIAG=$diag
export C3_PLAYBACK_ENABLE="${C3_PLAYBACK_ENABLE:-1}"
C3_ZOOM_AE_LOCK=1 C3_METER_DIAG=0 C3_SCORE_FULL_SP_ONLY=1 C3_PEAK_FULL_SP_ONLY=1 C3_DMA_UNPACK=0 C3_PEAK_SP_CENTER_W=256 C3_FOCUS_GREEN=1 C3_LIVE_PROFILE=0 \
 C3_FIFO_DMA_LIVE_ROWS=4 C3_FIFO_DMA_LIVE_TICKS=14 \
 C3_FIFO_DMA_LOAD=0 C3_FIFO_DMA_HIGH=0 C3_FIFO_DMA_MARGIN=0 C3_FIFO_DMA_PROBE=0 \
 C3_PEAK_EXPERIMENT=4 C3_PEAK_PROFILE=0 C3_PREVIEW_PROFILE=0 \
 C3_ROW_PACK16=0 C3_FIFO_ROW_ARM=0 C3_FIFO_ASM_MODE=0 C3_FIFO_CPU_BURST_BYTES=0 \
 C3_DNG_ACR_MODE=1 C3_DNG_FAST_SETTLE_FRAMES=2 C3_4X_FAST_8000=1 \
 C3_BUILD_TAG="${C3_BUILD_TAG:-V208_${variant}_ACR8_F2}" bash build_v182.sh
