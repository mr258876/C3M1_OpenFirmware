#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
variant="${1:-BOOT}"
case "$variant" in
  BOOT) overlap=1; boot_diag=0; lcd=1000;;
  BOOT500) overlap=1; boot_diag=0; lcd=500;;
  BOOT_PROFILE) overlap=1; boot_diag=1; lcd=1000;;
  BASE_PROFILE) overlap=0; boot_diag=1; lcd=1000;;
  *) echo 'usage: build_v206.sh BOOT|BOOT500|BOOT_PROFILE|BASE_PROFILE' >&2; exit 2;;
esac
profile=0; diag=0
export C3_BOOT_OVERLAP=$overlap C3_BOOT_DIAG=$boot_diag C3_LCD_POWER_SETTLE_MS=$lcd
C3_ZOOM_AE_LOCK=1 C3_METER_DIAG=$diag C3_SCORE_FULL_SP_ONLY=1 C3_PEAK_FULL_SP_ONLY=1 C3_DMA_UNPACK=0 C3_PEAK_SP_CENTER_W=256 C3_FOCUS_GREEN=1 C3_LIVE_PROFILE=$profile \
 C3_FIFO_DMA_LIVE_ROWS=4 C3_FIFO_DMA_LIVE_TICKS=14 \
 C3_FIFO_DMA_LOAD=0 C3_FIFO_DMA_HIGH=0 C3_FIFO_DMA_MARGIN=0 C3_FIFO_DMA_PROBE=0 \
 C3_PEAK_EXPERIMENT=4 C3_PEAK_PROFILE=0 C3_PREVIEW_PROFILE=0 \
 C3_ROW_PACK16=0 C3_FIFO_ROW_ARM=0 C3_FIFO_ASM_MODE=0 C3_FIFO_CPU_BURST_BYTES=0 \
 C3_DNG_ACR_MODE=1 C3_DNG_FAST_SETTLE_FRAMES=2 C3_4X_FAST_8000=1 \
 C3_BUILD_TAG="V206_${variant}_ACR8_F2" bash build_v182.sh
