#!/usr/bin/env python3
"""Check 60 C writer fixtures for all three modes and actual storage mock DNGs.
Usage: test_v182_acr.py TEST_DIR [original diagnostic ZIP]
"""
from pathlib import Path
import sys,io,zipfile
import numpy as np
import tifffile
w=Path(sys.argv[1]); n=642*480; stride=680
raw=np.arange(n,dtype=np.uint8); raw16=(raw.astype('<u2')*256).astype('<u2')
blobs=[(w/f'meta{i}.bin').read_bytes() for i in range(3)]
assert all(len(b)==60*stride for b in blobs)
def read(buf):
    with tifffile.TiffFile(io.BytesIO(buf)) as t:
        p=t.pages[0]; tags={x.code:(int(x.dtype),x.count,x.value) for x in p.tags.values()}
        for x in p.tags.values():
            if x.valuebytecount>4:
                assert 350<=x.valueoffset<x.valueoffset+x.valuebytecount<=512 or 512+p.tags[279].value[0]<=x.valueoffset<x.valueoffset+x.valuebytecount<=len(buf)
        return tags,p.asarray()
def compose(mode,i,pixels=raw):
    m=blobs[mode][i*stride:(i+1)*stride]
    data=(pixels.astype('<u2')*256).astype('<u2') if mode==2 else pixels
    return m[:512]+data.tobytes()+m[512:]
errors=[]
for i in range(60):
    base,p=read(compose(0,i)); assert np.array_equal(p.ravel(),raw)
    numer=base[50714][2][::2]; assert base[50714][2][1::2]==(1000,)*4
    for mode in (1,2):
        b=compose(mode,i); t,p=read(b)
        assert t.keys()==base.keys()
        assert p.shape==(480,642) and p.dtype==(np.uint8 if mode==1 else np.uint16)
        assert np.array_equal(p.ravel(),raw if mode==1 else raw16)
        for tag in t:
            if tag not in (258,279,50713,50714,50717): assert t[tag]==base[tag],(i,mode,tag)
        if mode==1:
            mean=(sum(numer)+2)//4
            assert t[50713]==(3,2,(1,1)) and t[50714]==(5,1,(mean,1000))
            assert t[258][2]==8 and t[279][2]==(n,) and t[50717][2]==255
            if i<45: errors.extend((np.array(numer)-mean)/1000)
        else:
            assert t[50713]==(3,2,(2,2)) and t[50714]==(5,4,tuple(z for v in numer for z in (v*256,1000)))
            assert t[258][2]==16 and t[279][2]==(2*n,) and t[50717][2]==65280
        assert len(b)==512+(n if mode==1 else 2*n)+168
        assert t[273][2]==(512,)
print('PASS 120 ACR-mode DNG fixtures: LUT, readback/interpolation, strip, metadata, RAW lossless, WB/profile unchanged')
print(f'Scalar residual over 180 calibrated CFA means: RMS {np.sqrt(np.mean(np.square(errors))):.6f} RAW8 DN; max abs {max(map(abs,errors)):.6f} DN')
# Independent decode of bytes generated by actual production storage C path.
ref=np.fromfunction(lambda y,x: ((y*644+x)*17+43)%256,(480,642),dtype=int).astype(np.uint8)
for mode in (0,1,2):
    b=(w/f'retry{mode}.dng').read_bytes(); t,p=read(b)
    assert np.array_equal(p,ref if mode!=2 else ref.astype(np.uint16)*256)
    assert t[50714][2]==((12854+13510+14941+15475+2)//4,1000) if mode==1 else t[50714][2]==tuple(z for v in (12854,13510,14941,15475) for z in (v*(256 if mode==2 else 1),1000))
    assert (w/f'retry{mode}.bmp').read_bytes()==(w/'retry0.bmp').read_bytes()
print('PASS actual storage DNG/BMP: exact FIFO row crop, endian, scaled black/white, complete tail, BMP unchanged')
if len(sys.argv)>2:
    with zipfile.ZipFile(sys.argv[2]) as z:
        for mode,prefix in ((1,'E_'),(2,'H_')):
            accepted=z.read(next(n for n in z.namelist() if n.startswith(prefix)))
            at,ap=read(accepted)
            input8=(ap//256).astype(np.uint8) if mode==2 else ap
            b=bytearray(compose(mode,22,input8))
            # Diagnostic uses original scene WB, rather than mock register WB.
            with tifffile.TiffFile(io.BytesIO(accepted)) as tt: a=tt.pages[0].tags[50728].valueoffset
            with tifffile.TiffFile(io.BytesIO(b)) as tt: o=tt.pages[0].tags[50728].valueoffset
            b[o:o+24]=accepted[a:a+24]
            bt,bp=read(b)
            assert bt==at and np.array_equal(bp,ap),(mode,[(k,bt[k],at[k]) for k in at if bt[k]!=at[k]])
            # H has exactly the same bytes; E has 24 unreferenced tail bytes zeroed.
            if mode==2: assert bytes(b)==accepted
            else: assert bytes(b)[:-24]==accepted[:-24] and bytes(b)[-24:]==bytes(24)
    print('PASS exact H fixture bytes and E referenced values match user-accepted test DNGs (E only clears 24 unused bytes)')
