#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
case "${1:-SP224}" in
 SP224) w=224; profile=0;;
 SP256) w=256; profile=0;;
 SP224_PROFILE) w=224; profile=1;;
 SP256_PROFILE) w=256; profile=1;;
 GREEN_REF) w=160; profile=0;;
 *) echo 'usage: build_v200.sh SP224|SP256|SP224_PROFILE|SP256_PROFILE|GREEN_REF' >&2; exit 2;;
esac
C3_PEAK_SP_CENTER_W=$w C3_FOCUS_GREEN=1 C3_LIVE_PROFILE=$profile \
 C3_FIFO_DMA_LIVE_ROWS=4 C3_FIFO_DMA_LIVE_TICKS=14 \
 C3_FIFO_DMA_LOAD=0 C3_FIFO_DMA_HIGH=0 C3_FIFO_DMA_MARGIN=0 C3_FIFO_DMA_PROBE=0 \
 C3_PEAK_EXPERIMENT=4 C3_PEAK_PROFILE=0 C3_PREVIEW_PROFILE=0 \
 C3_ROW_PACK16=0 C3_FIFO_ROW_ARM=0 C3_FIFO_ASM_MODE=0 C3_FIFO_CPU_BURST_BYTES=0 \
 C3_DNG_ACR_MODE=1 C3_DNG_FAST_SETTLE_FRAMES=2 C3_4X_FAST_8000=1 \
 C3_BUILD_TAG="V200_${1:-SP224}_ACR8_F2" bash build_v182.sh
